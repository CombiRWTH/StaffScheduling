INSERT INTO TPlanPersonalKommtGeht (RefPlan, RefPersonal, Datum, RefStati, lfdNr, RefgAbw, RefBerufe,
    RefPlanungseinheiten, RefDienstAbw, Minuten, Wunschdienst, RefPeinheitOwner)
SELECT p.Prim, v.emp, v.day, 20, 1, 20, h.RefBerufe, v.unit, 20, 0, 0, v.unit
FROM #vacation v
JOIN TPlan p ON p.RefPlanungseinheiten = v.unit AND p.VonDat = v.plan_start AND p.RefStati = 20
    AND p.RefPlanungsIntervalle = 1
JOIN TPlanungseinheitenPersonal h ON h.RefPersonal = v.emp AND h.RefPlanungseinheiten = v.unit AND h.IstHeimat = 1
    AND h.VonDat <= v.day AND h.BisDat >= v.day
WHERE NOT EXISTS (SELECT 1 FROM TPlanPersonalKommtGeht k
    WHERE k.RefPersonal = v.emp AND k.Datum = v.day AND k.RefStati = 20 AND k.lfdNr = 1)
GO
INSERT INTO TPersonalKontenJeTag (RefPersonal, Datum, RefKonten, Wert, WertSoll, RefPlanungsEinheiten, RefBerufe)
SELECT v.emp, v.day, 85, v.hours, v.hours, v.unit, h.RefBerufe
FROM #vacation v
JOIN TPlanungseinheitenPersonal h ON h.RefPersonal = v.emp AND h.RefPlanungseinheiten = v.unit AND h.IstHeimat = 1
    AND h.VonDat <= v.day AND h.BisDat >= v.day
WHERE EXISTS (SELECT 1 FROM TPlanPersonalKommtGeht k WHERE k.RefPersonal = v.emp AND k.Datum = v.day
        AND k.RefStati = 20 AND k.lfdNr = 1 AND k.RefgAbw = 20 AND k.RefDienstAbw = 20)
    AND NOT EXISTS (SELECT 1 FROM TPersonalKontenJeTag t
        WHERE t.RefPersonal = v.emp AND t.Datum = v.day AND t.RefKonten = 85)
GO
SELECT COUNT(*) AS expected,
    SUM(CASE WHEN k.RefgAbw = 20 AND k.RefDienstAbw = 20 AND ISNULL(k.Wunschdienst, 0) = 0 THEN 1 ELSE 0 END) AS absences,
    SUM(CASE WHEN ABS(t.Wert - v.hours) < 0.001 THEN 1 ELSE 0 END) AS credits,
    CASE WHEN COUNT(*) = 250
        AND SUM(CASE WHEN k.RefgAbw = 20 AND k.RefDienstAbw = 20 AND ISNULL(k.Wunschdienst, 0) = 0 THEN 1 ELSE 0 END) = 250
        AND SUM(CASE WHEN ABS(t.Wert - v.hours) < 0.001 THEN 1 ELSE 0 END) = 250 THEN 1 ELSE 0 END AS ok
FROM #vacation v
LEFT JOIN TPlanPersonalKommtGeht k ON k.RefPersonal = v.emp AND k.Datum = v.day AND k.RefStati = 20 AND k.lfdNr = 1
LEFT JOIN TPersonalKontenJeTag t ON t.RefPersonal = v.emp AND t.Datum = v.day AND t.RefKonten = 85
GO
